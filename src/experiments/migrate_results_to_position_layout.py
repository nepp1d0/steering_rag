"""
One-off migration: make the direction position a path component of retrieval results.

Old layout:  .../<procedure>/layer_<L>/{results.jsonl, retrieval_plot.png, *.pt, docs.jsonl}
New layout:  .../<procedure>/layer_<L>/last_pos/{results.jsonl, retrieval_plot.png}
             (tensors + docs.jsonl stay at the layer level: documents are always
              projected at their last token, so they are shared by every position)

Also renames top_layers_<procedure>.json -> top_layers_<procedure>_last_pos.json and
deletes aggregated_plots/ dirs (regenerated by plot_retrieval_evaluation with
position-aware names).

Idempotent. Run once per machine (local and cluster) on:
    results/retrieval_evaluation/  and  results/top_retrieval_evaluation/

Usage:
    python -m src.experiments.migrate_results_to_position_layout
"""

from __future__ import annotations

import shutil
import sys
from pathlib import Path

sys.path.append(str(Path(__file__).resolve().parents[2]))
from src.utils import RESULTS_DIR, logger

ROOTS = [RESULTS_DIR / "retrieval_evaluation", RESULTS_DIR / "top_retrieval_evaluation"]
POSITIONS = ("last_pos", "entity_pos")
MOVED_FILES = ("results.jsonl", "retrieval_plot.png")


def main() -> None:
    for root in ROOTS:
        if not root.exists():
            logger.info(f"Skip (missing): {root}")
            continue
        n_moved = n_renamed = n_plots = 0
        for f in sorted(root.rglob("results.jsonl")):
            layer_dir = f.parent
            if not layer_dir.name.startswith("layer_"):
                continue  # already migrated (parent is a position dir) or legacy layout
            tgt = layer_dir / "last_pos"
            tgt.mkdir(exist_ok=True)
            for name in MOVED_FILES:
                src = layer_dir / name
                if src.exists():
                    src.rename(tgt / name)
                    n_moved += 1
        for j in sorted(root.rglob("top_layers_*.json")):
            stem = j.stem.replace("top_layers_", "")
            if any(stem.endswith(p) for p in POSITIONS):
                continue
            j.rename(j.with_name(f"top_layers_{stem}_last_pos.json"))
            n_renamed += 1
        for d in sorted(root.rglob("aggregated_plots")):
            shutil.rmtree(d)
            n_plots += 1
        logger.info(f"{root.name}: moved {n_moved} files into last_pos/, renamed {n_renamed} "
                    f"top_layers jsons, removed {n_plots} aggregated_plots dirs")


if __name__ == "__main__":
    main()
